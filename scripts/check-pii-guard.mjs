#!/usr/bin/env node
/**
 * Проверки фильтра персональных данных (src/lib/pii-guard.ts).
 *
 * Запуск: node --experimental-strip-types scripts/check-pii-guard.mjs
 * (или npm run check:pii-guard)
 *
 * Фильтр стоит на входе очереди ИИ-агента: запрос уходит во внешний AI-сервис,
 * поэтому текст с реальными ПД блокируется до постановки в очередь. Отдельная
 * беда — ложные срабатывания: техническое задание перечисляет КАТЕГОРИИ данных
 * («ФИО, СНИЛС, паспортные данные, адрес регистрации, банковские реквизиты»),
 * и старый фильтр принимал названия категорий за сами данные.
 *
 * Проверяем обе стороны:
 *
 * 1. Техническая инструкция о защите ПД без реальных значений → проходит.
 * 2. Запрос с реальным телефоном / e-mail / идентификатором физлица → блок.
 * 3. Запрос с несколькими реальными ПД сразу → блок, категорий ≥ 2.
 * 4. Обычная задача по сайту (без ПД) → проходит.
 *
 * Плюс: обезличивание (anonymizePrompt) не трогает инструкцию и маскирует
 * реальное значение.
 *
 * Код возврата: 0 — все проверки прошли, 1 — есть ошибки (помечены ✗).
 */

import { checkPromptForPii, anonymizePrompt } from '../src/lib/pii-guard.ts'

let failed = 0
let passed = 0

/** Условие с человекочитаемым отчётом. */
function check(description, condition) {
  if (condition) {
    passed++
    console.log(`  ✓ ${description}`)
  } else {
    failed++
    console.error(`  ✗ ${description}`)
  }
}

/** Запрос должен пройти (ПД нет). */
function expectSafe(name, text) {
  console.log(`\n${name}`)
  const result = checkPromptForPii(text)
  check(`не заблокирован (получено: ${result.categories.join(', ') || '—'})`, result.safe)
  return result
}

/** Запрос должен быть заблокирован; при categories — минимум столько категорий. */
function expectBlocked(name, text, minCategories = 1) {
  console.log(`\n${name}`)
  const result = checkPromptForPii(text)
  check(`заблокирован (категории: ${result.categories.join(', ') || '—'})`, !result.safe)
  check(
    `найдено категорий ≥ ${minCategories} (получено ${result.categories.length})`,
    result.categories.length >= minCategories,
  )
  return result
}

// 1. Техническая инструкция: только правила защиты, обезличивания и категории.
const TECH_INSTRUCTION = [
  'Техническое задание по защите персональных данных.',
  'Категории ПД в системе: ФИО, дата рождения, адрес регистрации,',
  'паспортные данные, СНИЛС, ИНН, банковские реквизиты,',
  'свидетельство о рождении, военный билет, полис ОМС.',
  'Перед отправкой во внешний ИИ-сервис данные нужно обезличивать:',
  'телефон, e-mail и адрес в промпт не попадают, вместо них — подписи вида',
  '«[телефон скрыто]». Место рождения и прописку тоже исключаем.',
].join(' ')
expectSafe('1. Техническая инструкция о защите ПД без реальных значений', TECH_INSTRUCTION)
check('инструкция не изменена обезличиванием', anonymizePrompt(TECH_INSTRUCTION) === TECH_INSTRUCTION)
check('перечислены все спорные категории',
  ['паспортные данные', 'снилс', 'дата рождения', 'адрес регистрации', 'банковские реквизиты', 'свидетельство о рождении']
    .every((s) => TECH_INSTRUCTION.toLowerCase().includes(s)))

// 2. Реальные значения по одному.
expectBlocked('2a. Реальный телефон', 'Позвони клиенту по номеру +7 988 123-45-67 и уточни время.')
expectBlocked('2b. Реальный e-mail', 'Отправь договор на client.ivanov@mail.ru.')
expectBlocked('2c. Идентификатор физлица — СНИЛС', 'Проверь СНИЛС 123-456-789 00 в заявлении.')
expectBlocked('2d. Идентификатор физлица — ИНН', 'Уточни ИНН 7707083893 в налоговой.')
expectBlocked('2e. Идентификатор физлица — паспорт', 'Сверь паспорт 4506 123456 с анкетой.')
// Слово «паспорт» без номера — это категория, а не данные (см. тест 1), а вот
// строка ниже содержит ещё и ФИО — её блокирует именно значение.
expectBlocked('2f. ФИО + телефон', 'Клиент Иван Петров, телефон 8 988 765-43-21.')

// 3. Несколько реальных ПД одновременно.
const multiple = expectBlocked(
  '3. Несколько реальных ПД одновременно',
  'Клиент Иванов Иван Иванович, тел. +7 (988) 111-22-33, e-mail ivanov@example.com, ' +
    'СНИЛС 123-456-789 00, паспорт 4506 123456.',
  2,
)
check(
  'сработали разные категории (телефон, e-mail, СНИЛС/паспорт)',
  multiple.categories.includes('phone') &&
    multiple.categories.includes('email') &&
    (multiple.categories.includes('snils') || multiple.categories.includes('passport')),
)

// 4. Обычная задача по сайту.
expectSafe(
  '4. Обычная задача по сайту',
  'На главной странице добавь блок с новостями, поправь отступы у карточек объектов ' +
    'и проверь адаптив на 390 px. Цвета — по токенам из globals.css.',
)

// Дополнительно: обезличивание реального значения.
console.log('\nДополнительно: обезличивание')
const masked = anonymizePrompt('Телефон клиента +7 988 123-45-67, e-mail client@mail.ru.')
check('телефон заменён подписью', masked.includes('[телефон скрыто]') && !masked.includes('123-45-67'))
check('e-mail заменён подписью', masked.includes('[электронная почта скрыто]') && !masked.includes('client@mail.ru'))

console.log(`\nИтог: ${passed} успешно, ${failed} с ошибкой`)
process.exit(failed === 0 ? 0 : 1)
