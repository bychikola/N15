/**
 * Иерархия фильтра «Город» каталога: регион → населённые пункты.
 *
 * Файл — структура списка (порядок и подписи регионов), без данных: сами
 * населённые пункты и счётчики объектов собирает серверная часть из
 * справочника CRM (см. loadCatalogCityFilter в src/lib/interregional-service.ts).
 * Сотрудник заводит населённый пункт в CRM — он появляется в фильтре, а не в
 * коде; здесь только то, что задано списком регионов: Северная Осетия —
 * Алания, Москва, Московская область, Краснодарский край, Ставропольский
 * край, Республика Адыгея, Санкт-Петербург и Ленинградская область,
 * Республика Крым и «Другие регионы» (города с объектами,
 * которых нет в справочнике).
 * Регион справочника «Москва и Московская область» показывается двумя
 * строками — по его подгруппам «Москва» и «Московская область».
 *
 * Населенные пункты Осетии лежат в поле «Населённый пункт» адреса
 * (address.locality), межрегиональные города — в поле «Город» (address.city);
 * фильтр ищет значение в своём поле (field). Названия агенты вводят руками,
 * поэтому рядом с каноническим значением фильтр шлёт написания, найденные в
 * базе (values): «Химки», «химки», «Химки » — объект находится, как бы он ни
 * был записан, а счётчик рядом с пунктом считает по тем же значениям.
 */

/** Поле адреса, в котором живёт значение фильтра */
export type CityFilterField = 'city' | 'locality'

/** Условие фильтра «Все населённые пункты региона»: что искать в адресе */
export interface CityFilterMatch {
  field: CityFilterField
  /** Значения для where (канонические названия и написания из базы) */
  values: string[]
}

/** Населенный пункт в списке региона */
export interface CityFilterPlace {
  /** Значение фильтра (пункт списка) */
  value: string
  label: string
  /** Поле адреса, по которому ищем (см. CityFilterField) */
  field: CityFilterField
  /** Сколько опубликованных объектов в населённом пункте */
  count: number
  /** Значения для where: каноническое название и написания из базы */
  values: string[]
}

/** Регион верхнего уровня — раскрывается в населённые пункты */
export interface CityFilterRegion {
  /** Ключ региона — значение параметра city_region ссылки каталога */
  key: string
  label: string
  /** Осетия: населённые пункты республики живут в address.locality. У
   *  остальных регионов города межрегиональные — address.city. Участки
   *  ищутся только по Осетии (межрегиональных направлений у земли нет) */
  ossetian: boolean
  /** Сколько опубликованных объектов в регионе (строка «все населённые пункты») */
  count: number
  /** Условия строки «Все населённые пункты региона». Пусто — в регионе нет
   *  ни одного населённого пункта (условие фильтра построить не из чего) */
  match: CityFilterMatch[]
  places: CityFilterPlace[]
}

/** Регион списка и его источник в справочнике CRM */
interface CityFilterRegionSource {
  key: string
  label: string
  /** Название региона в CRM; без него строка — Осетия: её населённые пункты
   *  не межрегиональные, а республиканские (см. OSSETIA_TOWNS) */
  crmRegion?: string
  /** Подгруппа внутри региона CRM — «Москва» и «Московская область» в
   *  справочнике «Москва и Московская область». Без подгруппы в строку
   *  фильтра идут все населённые пункты региона CRM */
  crmGroup?: string
}

