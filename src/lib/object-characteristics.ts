/**
 * Характеристики объекта, которые в CRM выбирают из списка: состояние
 * (ремонт), отопление, лифт и парковка.
 *
 * В базе это текстовые поля, а не select: старые карточки хранят свободный
 * текст («Космет. ремонт», «Есть лифт»), и запрещать своё значение нельзя.
 * Справочник питает подсказки формы объекта (datalist) и подписи фильтров
 * каталога. Select-полем поле стало бы enum в postgres, а новые значения
 * enum drizzle-push не умеет (см. memory payload-schema-autopush) — поэтому
 * список живёт в коде, а не в схеме коллекции.
 *
 * Прежние значения из подсказок не убираем никогда: в базе есть объекты с
 * ними, и агент должен узнавать свои прежние формулировки в списке.
 */

