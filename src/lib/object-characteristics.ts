/**
 * Есть ли у объекта само строение: у земельного участка ни ремонта, ни
 * отопления не бывает — он описывается площадью, категорией земель и
 * коммуникациями по границе.
 */
const isBuildingCategory = (category: string): boolean => category !== 'land'

/** Состояние (ремонт): у всего, что построено, — кроме земельного участка */
export const conditionAppliesTo = isBuildingCategory

/** Отопление: у всего, что построено, — кроме земельного участка */
export const heatingAppliesTo = isBuildingCategory

/**
 * Лифт: у квартир, комнат и коммерции в многоквартирных домах. У частного
 * дома, дачи, гаража и участка лифта нет.
 */
export const elevatorAppliesTo = (category: string): boolean =>
  category === 'apartment' || category === 'room' || category === 'commercial'

/**
 * Парковка: у квартиры, комнаты и коммерции — общие места дома, у домовых
 * категорий — двор, гараж и машиноместо. У участка и гаража поля нет: у
 * гаража парковкой является сам объект.
 */
export const parkingAppliesTo = (category: string): boolean =>
  isBuildingCategory(category) && category !== 'garage'
