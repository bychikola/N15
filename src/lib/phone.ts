/**
 * Телефоны к одному виду: «+7 (918) 828-40-88».
 *
 * Агенты вводят номера как привыкли — 8 918 828 40 88, +79188284088,
 * 9188284088, — и в списках рядом оказывались «+7 (918) 828-40-88» и
 * «+79188255353». Функции ниже приводят запись к одному виду: на сохранении
 * (хук коллекции agents — правка из админки, из CRM и через API одинаково)
 * и на чтении (хук afterRead — старые записи тоже показываются ровно, без
 * разовой правки базы).
 *
 * Что НЕ трогаем: строки с буквами и всё, что не похоже на российский номер
 * (городской с добавочным, иностранный, заметка вроде «звонить после 18:00»).
 * Испортить то, что человек написал осознанно, хуже, чем оставить как есть.
 */

/** Буквы в значении — это уже не номер: ссылка wa.me, заметка, добавочный */
const hasLetters = (v: string): boolean => /[a-zA-Zа-яА-Я]/.test(v)

/** Цифры российского номера без кода страны: 10 штук, либо пусто */
const ruDigits = (raw: string): string => {
  const d = raw.replace(/\D/g, '')
  if (d.length === 11 && (d[0] === '7' || d[0] === '8')) return d.slice(1)
  if (d.length === 10) return d
  return ''
}

/** «9188284088» → «+7 (918) 828-40-88» */
const pretty = (d: string): string =>
  `+7 (${d.slice(0, 3)}) ${d.slice(3, 6)}-${d.slice(6, 8)}-${d.slice(8, 10)}`

/**
 * Канонический вид номера. Если значение не похоже на российский номер,
 * возвращаем его как есть — и на сохранении, и на чтении.
 */
export const formatRuPhone = (raw: string): string => {
  if (!raw || hasLetters(raw)) return raw
  const d = ruDigits(raw)
  return d ? pretty(d) : raw
}

/**
 * Маска для поля ввода: подставляет скобки и дефисы по мере набора, чтобы
 * сотрудник видел номер в том же виде, в каком он попадёт в карточку.
 * Работает и с недонабранным номером («918» → «+7 (918)»), поэтому
 * используется в onChange, а не только при сохранении.
 *
 * Значения с буквами (ссылка wa.me, заметка) пропускаем без изменений —
 * иначе маска съела бы их при вводе.
 */
export const maskRuPhoneInput = (raw: string): string => {
  if (!raw || hasLetters(raw)) return raw
  let d = raw.replace(/\D/g, '')
  if (!d) return ''
  // Ведущие 7/8 — код страны: в маске он уже есть, второй раз не нужен
  if (d[0] === '7' || d[0] === '8') d = d.slice(1)
  d = d.slice(0, 10)
  if (!d) return '+7'

  let out = `+7 (${d.slice(0, 3)}`
  if (d.length >= 3) out += ')'
  if (d.length > 3) out += ` ${d.slice(3, 6)}`
  if (d.length > 6) out += `-${d.slice(6, 8)}`
  if (d.length > 8) out += `-${d.slice(8, 10)}`
  return out
}
