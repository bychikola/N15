/**
 * Примерная область объекта — то, что видит посетитель сайта на карте.
 * Точных меток у объектов на публичной части нет: вместо точки показывается
 * круг области, внутри которой объект находится, а подписью к ней идут район,
 * город или населённый пункт (см. src/lib/object-public-address.ts).
 *
 * Область считает сетка, а не секрет приложения, и это главное её свойство:
 *   • центр круга — центр клетки сетки, а не координаты дома. Объект может
 *     стоять в любой точке клетки, поэтому по кругу не определить ни дом, ни
 *     сторону улицы: радиус равен половине диагонали клетки, и настоящая точка
 *     всегда внутри;
 *   • сетка одна на всю карту: сколько бы раз посетитель ни открывал карту и
 *     как бы ни сужал фильтры, область у объекта одна и та же — усреднить
 *     показы до точного адреса нельзя;
 *   • объекты одной клетки показываются одной областью (см. mapAreas в
 *     src/lib/object-map-point.ts): отдельные круги на соседних точках
 *     нарисовались бы друг на друге и слились бы в пятно.
 *
 * Модуль общий для сервера и клиента: секрета в нём нет, и клиент считает ту
 * же область по координатам, которые сам получил от геокодера (карта объекта
 * без отмеченных агентом координат, см. ObjectMap). Координаты объектов в CRM
 * (форма объекта, карточка агента) — не про этот модуль: там точка точная.
 */

/** Шаг сетки примерной области, метры: точнее этого объект не показывается */
export const APPROX_CELL_M = 700

/**
 * Радиус круга области, метры: половина диагонали клетки плюс запас. Запас
 * нужен потому, что масштаб долготы считается по широте центра клетки, а на
 * её краю долгота чуть короче: без запаса точка в углу клетки оказалась бы в
 * паре сантиметров за кругом
 */
export const APPROX_RADIUS_M = Math.ceil(APPROX_CELL_M * Math.SQRT1_2) + 1

/**
 * Предел приближения публичной карты. Ближе объект виден по отдельным домам, а
 * публичная карта показывает только примерную область — приближение
 * ограничиваем, чтобы по карте нельзя было прочитать адрес. В CRM предел не
 * ставится: агенту и администратору нужна точная карта (см. CrmObjects).
 */
export const APPROX_MAX_ZOOM = 16

/** Примерная область: центр круга и его радиус */
export interface ApproxPoint {
  /** Клетка сетки — объекты одной клетки показываются одной областью */
  key: string
  lat: number
  lng: number
  /** Радиус области в метрах — настоящая точка объекта внутри неё */
  radius: number
}

/** Метров в градусе широты (долгота короче — её считаем через cos широты) */
const METERS_PER_DEGREE = 111_320

/**
 * Точные координаты → примерная область (null — координат нет).
 * Клетку считаем по широте, а по её центру — масштаб долготы: тогда клетка на
 * земле квадратная, и половина её диагонали равна APPROX_RADIUS_M.
 */
export function approximatePoint(coords: [number, number] | null | undefined): ApproxPoint | null {
  if (!coords) return null
  const [lat, lng] = coords
  const row = Math.floor((lat * METERS_PER_DEGREE) / APPROX_CELL_M)
  const centerLat = ((row + 0.5) * APPROX_CELL_M) / METERS_PER_DEGREE
  // Долгота у полюсов вырождается (cos → 0): ограничиваем знаменатель, чтобы
  // область не улетала за край карты
  const lngScale = METERS_PER_DEGREE * Math.max(Math.cos((centerLat * Math.PI) / 180), 0.2)
  const col = Math.floor((lng * lngScale) / APPROX_CELL_M)
  return {
    key: `${row}:${col}`,
    lat: centerLat,
    lng: ((col + 0.5) * APPROX_CELL_M) / lngScale,
    radius: APPROX_RADIUS_M,
  }
}
