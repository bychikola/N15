/**
 * Приблизительная точка объекта — то, что видит посетитель сайта на карте.
 * Точные координаты дома на публичной части не показываем: метка ставится в
 * стороне от объекта, а вокруг неё рисуется область (радиус APPROX_RADIUS_M),
 * внутри которой объект находится. Определить по такой метке конкретный дом
 * нельзя, а район поиска клиент видит.
 *
 * Смещение считает сервер и детерминированно: угол и удаление выводятся из
 * HMAC по id объекта с секретом приложения. Поэтому:
 *   • точка не «дрожит» при обновлении страницы — объект стоит на одном месте,
 *     и карта не выглядит сломанной;
 *   • повторные показы не усредняются до точных координат (сдвиг один и тот
 *     же, а из самого сдвига точку не восстановить — секрет есть только на
 *     сервере: у публичного ключа карты его нет);
 *   • удаление смещения меньше радиуса области, поэтому настоящая точка
 *     всегда внутри нарисованного круга.
 *
 * Модуль серверный (node:crypto): в браузер приблизительные координаты едут
 * готовыми числами вместе с радиусом, секрет и точные координаты — нет.
 * Координаты объектов в CRM (форма объекта, карточка агента) — не про этот
 * модуль: там точка ставится точная.
 */

import { createHmac } from 'node:crypto'

/** Радиус области, которой показывается объект на публичной карте, метры */
export const APPROX_RADIUS_M = 300

/** Приблизительная точка: координаты метки и радиус области вокруг неё */
export interface ApproxPoint {
  lat: number
  lng: number
  /** Радиус области в метрах — настоящая точка объекта внутри неё */
  radius: number
}

/** Метров в градусе широты (долгота короче — её считаем через cos широты) */
const METERS_PER_DEGREE = 111_320

/** Секрет приложения: тот же, что у Payload (см. payload.config.ts) */
function secret(): string {
  return process.env.PAYLOAD_SECRET || 'n15-dev-secret-change-in-production'
}

/**
 * Точные координаты → приблизительная точка (null — координат нет).
 * seed — id объекта: у каждого объекта своё смещение, но всегда одно и то же.
 */
export function approximatePoint(
  coords: [number, number] | null | undefined,
  seed: string | number,
): ApproxPoint | null {
  if (!coords) return null
  const [lat, lng] = coords
  const digest = createHmac('sha256', secret()).update(`object-map:${seed}`).digest()
  const unit = (offset: number) => digest.readUInt32BE(offset) / 0xffff_ffff

  // Угол смещения и удаление от дома: 0,35–0,85 радиуса (удаление меньше
  // радиуса области — настоящая точка остаётся внутри круга)
  const angle = unit(0) * 2 * Math.PI
  const distance = APPROX_RADIUS_M * (0.35 + 0.5 * unit(4))

  // Долгота у полюсов вырождается (cos → 0): ограничиваем знаменатель, чтобы
  // смещение не улетало за край карты
  const lngScale = METERS_PER_DEGREE * Math.max(Math.cos((lat * Math.PI) / 180), 0.2)
  return {
    lat: lat + (distance * Math.cos(angle)) / METERS_PER_DEGREE,
    lng: lng + (distance * Math.sin(angle)) / lngScale,
    radius: APPROX_RADIUS_M,
  }
}
