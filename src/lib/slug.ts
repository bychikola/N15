/**
 * URL-путь (slug) из русскоязычного названия — для справочников, которые
 * заводятся в CRM: регионы и населённые пункты межрегиональной недвижимости
 * (см. src/lib/interregional.ts).
 *
 * Пути латиницей: их видно в адресе страницы населённого пункта
 * (/ru/interregional/stavropolskiy-kray/stavropol), и такая ссылка не
 * превращается в %D0%9… при копировании. Транслитерация — практическая
 * (ГОСТ-подобная, без диакритики): «ё» → e, «й» → y, «ъ»/«ь» опускаются.
 * Файл самодостаточен — используется и в хуках коллекций, и в сиде.
 */

const TRANSLIT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'shch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

/**
 * Slug из названия: «Минеральные Воды» → «mineralnye-vody».
 * Латиница, цифры и дефис остаются как есть, прочие знаки — разделители.
 * Пустой результат (например, одно название из знаков) — пустая строка:
 * вызывающая сторона сама решает, чем заменить.
 */
export function translitSlug(text: string): string {
  const out = Array.from(text.toLowerCase())
    .map((ch) => (ch in TRANSLIT ? TRANSLIT[ch] : ch))
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
  return out
}
