/**
 * Объект в списке предложений города (блок на главной). Поля приходят из
 * REST объектов (address.city идёт отдельным ключом группы address).
 */
export interface InterregionalObject {
  id: number
  /** Числовой id или slug — оба понимает страница объекта (/catalog/<id|slug>) */
  slug: string | null
  title: string
  price: number | null
  type: 'sale' | 'rent'
  street: string | null
  house: string | null
}
