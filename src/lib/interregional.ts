/**
 * Справочник регионов «Межрегиональной недвижимости» — блока на главной
 * (строка-регион раскрывается в города и их предложения) и фильтра «Город»
 * в каталоге.
 *
 * Города — собственные имена, без перевода. У каждой подгруппы два списка:
 * - cities — ключевые города: в блоке видны всегда. Если опубликованных
 *   объектов в городе нет, рядом с городом стоит подпись «Объектов Н15 пока
 *   нет» (см. t.landing.countryCityNone); как только объекты появятся
 *   (address.city объекта), город оживает автоматически.
 * - extra — остальные города справочника: появляются в блоке, только когда
 *   в городе есть опубликованные объекты.
 *
 * «Новая Москва» и «Парголово» — не муниципальные образования: ТиНАО
 * Москвы и посёлок в составе Санкт-Петербурга. Они в справочнике, потому
 * что так их пишут в адресах объявлений (address.city) — строка сработает
 * как обычный город, когда такие объекты появятся.
 *
 * Порядок регионов — порядок строк блока на главной (нумерация 01-04).
 * Порядок городов внутри списка — приоритет показа (не алфавит).
 */
export interface InterregionalGroup {
  /** Подзаголовок подгруппы внутри строки региона («Москва», «Московская область»…) */
  label?: string
  /** Ключевые города: видны всегда, без объектов — с пометкой */
  cities: string[]
  /** Прочие города справочника: видны только при наличии объектов */
  extra?: string[]
}

export interface InterregionalRegion {
  title: string
  groups: InterregionalGroup[]
}

