/**
 * Справочник регионов «Межрегиональной недвижимости» — блока на главной
 * (строка-регион раскрывается в города) и фильтра «Город» в каталоге.
 *
 * Города — собственные имена, без перевода. В блоке показывается только
 * город, в котором есть опубликованные объекты (address.city объекта);
 * если объекты появятся в новом городе региона — допишите его сюда.
 * Внутри строки «Санкт-Петербург» Ленинградская область — отдельная
 * подгруппа (label), она видна, только когда в её городах есть объекты.
 */
export interface InterregionalGroup {
  /** Подзаголовок подгруппы внутри строки региона (например «Ленинградская область») */
  label?: string
  /** Города: первым — столица региона, дальше остальные в алфавитном порядке */
  cities: string[]
}

export interface InterregionalRegion {
  title: string
  groups: InterregionalGroup[]
}

