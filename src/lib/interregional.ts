/**
 * Ключ сравнения названий населённых пунктов: регистр, лишние пробелы и «ё»
 * не должны мешать («Будённовск» и «Буденновск» — один город). Значения
 * адресов объектов вводятся руками, поэтому сравнение терпимое.
 */
export const cityKey = (name: string): string =>
  name.trim().toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ')

/** Населённый пункт в списке региона (данные CRM + счётчик объектов) */
export interface InterregionalSettlement {
  id: number
  name: string
  slug: string
  /** Город, как он записан в адресах объектов (address.city) */
  city: string
  /** Подгруппа внутри региона («Московская область»), пусто — без подгруппы */
  group: string
  /** Категория объектов страницы населённого пункта (обычно «квартира») */
  category: string
  /** Тип сделки страницы: sale, rent или any (и продажа, и аренда) */
  dealType: string
  /** Сколько опубликованных объектов подходит под фильтр населённого пункта */
  count: number
}

export interface InterregionalRegion {
  id: number
  title: string
  slug: string
  groups: { label: string; settlements: InterregionalSettlement[] }[]
  /** Все населённые пункты региона одним списком (без подгрупп) */
  settlements: InterregionalSettlement[]
}

/** Город с опубликованными объектами, которого нет в справочнике CRM */
export interface InterregionalOtherCity {
  name: string
  count: number
}

/** Страница населённого пункта: /<язык>/interregional/<регион>/<населённый пункт> */
export const settlementHref = (lang: string, regionSlug: string, settlementSlug: string): string =>
  `/${lang}/interregional/${regionSlug}/${settlementSlug}`

/**
 * Каталог с фильтром населённого пункта — та же выборка, что показывает его
 * страница (город, категория, тип сделки), но со всеми фильтрами каталога
 * и пагинацией. Значения — те же, что понимает фильтр каталога.
 */
export function settlementCatalogHref(
  lang: string,
  settlement: Pick<InterregionalSettlement, 'name' | 'city' | 'category' | 'dealType'>,
): string {
  const params = new URLSearchParams({ city: settlement.city || settlement.name })
  if (settlement.category) params.set('category', settlement.category)
  if (settlement.dealType && settlement.dealType !== 'any') params.set('type', settlement.dealType)
  return `/${lang}/catalog?${params.toString()}`
}
