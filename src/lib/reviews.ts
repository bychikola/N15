/**
 * «Отзывы клиентов» — движок раздела (публичная страница /reviews и модерация
 * в CRM, раздел /crm/reviews).
 *
 * Отзыв оставляет посетитель сайта с формы «Оставить отзыв» (имя, оценка 1–5,
 * текст и необязательная услуга). На сайт отзыв попадает только после проверки
 * администратором: на модерации → опубликован, либо отклонён, либо скрыт.
 * Персональные данные сверх имени не собираем — ни телефона, ни адреса.
 *
 * Модуль без зависимостей (как src/lib/board.ts и src/lib/developers.ts):
 * одни и те же подписи статусов и правила публикации используют и коллекция
 * админки, и маршруты, и интерфейс CRM — значения не разъезжаются.
 *
 * ВАЖНО: набор и ПОРЯДОК значений select-поля status совпадают с enum в базе.
 * При добавлении статуса значение сначала до-добавляется в БД (ALTER TYPE,
 * см. docker-entrypoint.sh), иначе dev-push пытается пересобрать enum и зависает.
 */

// --- Статусы ---------------------------------------------------------------------

/**
 * Статус отзыва. Путь: на модерации → (опубликован | отклонён | скрыт).
 * «Скрыт» — уже проверенный отзыв, снятый с показа без отказа (например,
 * клиент попросил убрать или текст устарел); из «скрытых» его можно вернуть
 * на проверку, из «отклонённых» — тоже.
 */
export type ReviewStatus = 'pending' | 'published' | 'rejected' | 'hidden'

export const REVIEW_STATUS_LABELS: Record<ReviewStatus, string> = {
  pending: 'Ждут проверки',
  published: 'Опубликованы',
  rejected: 'Отклонены',
  hidden: 'Скрыты',
}

export const REVIEW_STATUS_OPTIONS = (Object.keys(REVIEW_STATUS_LABELS) as ReviewStatus[]).map(
  (value) => ({ label: REVIEW_STATUS_LABELS[value], value }),
)

/** Отзыв виден на сайте: опубликован и не скрыт */
export const reviewVisible = (status: unknown): boolean => status === 'published'

// --- Оценка ----------------------------------------------------------------------

/** Оценки — целые звёзды от 1 до 5 */
export const REVIEW_MIN_RATING = 1
export const REVIEW_MAX_RATING = 5

/** Оценка из значения формы: целое 1–5, иначе null (значение не годится) */
export const reviewRating = (value: unknown): number | null => {
  const n = Number(value)
  if (!Number.isInteger(n) || n < REVIEW_MIN_RATING || n > REVIEW_MAX_RATING) return null
  return n
}

