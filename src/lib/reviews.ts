// --- Типы для проверок -----------------------------------------------------------

/** Поля отзыва, которые нужны движку (Payload отдаёт документ) */
export interface ReviewLike {
  status?: string | null
  name?: string | null
  rating?: number | null
  text?: string | null
  service?: string | null
  consent?: boolean | null
  publishedAt?: string | null
}

// --- Правила ---------------------------------------------------------------------

/** Какой-нибудь текст без учёта пробелов */
const filled = (v: unknown): boolean => Boolean(String(v ?? '').trim())

/**
 * Почему отзыв нельзя опубликовать (null — можно). Проверка одна на всех:
 * её вызывает и кнопка «Опубликовать» в CRM, и маршрут модерации, и хук
 * коллекции — на сайт не попадёт отзыв без имени, оценки, текста или согласия.
 */
export const reviewPublishIssue = (review: ReviewLike): string | null => {
  if (!filled(review.name)) return 'Не указано имя автора отзыва'
  if (reviewRating(review.rating) === null) return 'Не указана оценка (1–5 звёзд)'
  if (!filled(review.text)) return 'Не заполнен текст отзыва'
  if (review.consent !== true) return 'Нет согласия на обработку персональных данных'
  return null
}

