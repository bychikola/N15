/**
 * Склонение по-русски: «1 отзыв», «2 отзыва», «5 отзывов». Для нуля — «отзывов»
 * («0 отзывов»). Нужно только для подписи под сводкой оценок на сайте.
 */
export const reviewsCountLabel = (n: number): string => {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return 'отзыв'
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return 'отзыва'
  return 'отзывов'
}
