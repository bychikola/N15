/**
 * Кадастровый номер к одному виду: «15:07:0030021:123».
 *
 * Номер вводят в карточке объекта CRM, в админке Payload и через API, поэтому
 * правила формата живут в одном месте: их берут и форма (понятное сообщение до
 * отправки), и коллекция Objects (validate поля — тогда номер нельзя записать
 * мимо формы). Хранится номер только цифрами и двоеточиями: пробелы, дефисы и
 * прочие разделители при вводе не мешают, их снимает cleanCadastral.
 *
 * Юрэкспертиза (src/lib/legal-check.ts) пользуется теми же функциями — своего
 * разбора кадастрового номера у неё больше нет, чтобы формат не разъехался.
 */

/** Формат ЕГРН: 2 цифры — округ, 2 — район, 6–7 — квартал, 1–10 — объект */
export const CADASTRAL_FORMAT = /^\d{2}:\d{2}:\d{6,7}:\d{1,10}$/

/**
 * Убирает только пробелы и переносы: «15: 07:0030021:123 » → «15:07:0030021:123».
 *
 * Остальные символы остаются как есть — лишний знак в номере
 * («15:07:0030021:123/1») должен показать ошибку формата, а не превратиться
 * молча в другой номер («15:07:0030021:1231»), который потом уйдёт в карточку.
 */
export const cleanCadastral = (v?: string | null): string => (v || '').replace(/\s+/g, '').slice(0, 40)

/** Похож ли номер на кадастровый: «15:07:0030021:123» — да, «12345» — нет */
export const isCadastralFormat = (v?: string | null): boolean => CADASTRAL_FORMAT.test(cleanCadastral(v))
