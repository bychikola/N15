/**
 * Все документы с печатной формой: восемь из раздела «Документы» плюс три,
 * которые жили на сайте раньше и остались на своих страницах. По этому списку
 * собирается карта идентификаторов, а адрес выгрузки — /api/documents/<id>/pdf.
 */
export const LEGAL_DOC_PAGES: LegalDoc[] = [
  ...LEGAL_DOC_LIST,
  ADVERTISING_OFFER_DOC,
  ADVERTISING_RULES_DOC,
  BOARD_RULES_DOC,
]

/** Документы по идентификатору (страницы, ссылки форм, выгрузки) */
export const LEGAL_DOCS: Record<LegalDocId, LegalDoc> = LEGAL_DOC_PAGES.reduce(
  (acc, doc) => {
    acc[doc.id] = doc
    return acc
  },
  {} as Record<LegalDocId, LegalDoc>,
)

/** Документ по идентификатору (маршрут выгрузки /api/documents/[slug]) */
export const legalDocById = (id: string): LegalDoc | null =>
  LEGAL_DOC_PAGES.find((doc) => doc.id === id) || null

/** Документ страницы раздела «Документы» (последний кусок адреса = id) */
export const legalDocBySlug = (slug: string): LegalDoc | null =>
  LEGAL_DOC_LIST.find((doc) => doc.path.split('/').pop() === slug) || null

/**
 * Адрес документа с учётом языка сайта: /ru/documents/user-agreement.
 * Для политики вернёт её собственную страницу (/ru/privacy).
 */
export const legalDocHref = (lang: string, doc: LegalDoc): string => `/${lang}${doc.path}`

/** Имя файла выгрузки без расширения: n15-user-agreement.pdf */
export const legalDocFileBase = (doc: LegalDoc): string => `n15-${doc.id}`

/**
 * Ссылка на документ для формы: адрес и название. Клиентские компоненты
 * (галочки согласий) берут ссылки отсюда — модуль не тянет ни словарь, ни
 * генераторы файлов, поэтому попадает в браузерный бандл без лишнего.
 */
export interface LegalDocLink {
  id: LegalDocId
  path: string
  title: string
  short: string
}

export const legalDocLink = (id: LegalDocId): LegalDocLink => {
  const doc = LEGAL_DOCS[id]
  return { id, path: doc.path, title: doc.title, short: doc.short }
}

/** Ссылки на документы одним списком — для строки «Документы: …» под галочкой */
export const legalDocLinks = (...ids: LegalDocId[]): LegalDocLink[] => ids.map(legalDocLink)
