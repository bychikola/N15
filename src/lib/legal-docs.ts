/**
 * Правовые документы сайта Н15 — единый реестр раздела «Документы»
 * (/{lang}/documents и /{lang}/documents/<адрес>).
 *
 * Зачем отдельный модуль: до него документы были разбросаны по трём местам —
 * договор-оферта и правила рекламы в advertising-legal.ts, правила доски в
 * board-legal.ts, политика обработки данных в словаре сайта. Формам нужны
 * ссылки на конкретные документы, а человеку — печатная форма каждого из них,
 * поэтому у документов появился один список с адресами, версиями и датами.
 *
 * Тексты, которые уже были в проекте, здесь НЕ переписаны, а переиспользованы:
 * «Правила размещения объектов и рекламы» собраны из действующих редакций
 * правил доски и правил рекламы, «Политика обработки персональных данных»
 * живёт на своей странице /privacy (её текст двуязычный, см. словарь).
 * Новые документы (согласия, пользовательское соглашение, оферта на
 * размещение объекта) написаны по тем же правилам, что и прежние: у каждого
 * одна редакция, одна дата и одна версия, которая сохраняется в заявке —
 * принятая редакция не меняется задним числом при правке текста.
 *
 * ВАЖНО: перед публикацией документы проверяет юрист. Тексты ниже — рабочие
 * формулировки владельца и юриста не заменяют. При правке меняйте дату
 * редакции (LEGAL_UPDATED) и версию документа: заявки с прежней версией
 * остаются привязанными к той редакции, которую человек принимал.
 *
 * Реквизиты оператора берутся из advertising-legal.ts (AD_OPERATOR), чтобы
 * на сайте и в документах не разошлись контакты. ИНН и ОГРН в проекте нет:
 * если владелец их добавит, строка «Реквизиты» дополнится автоматически —
 * см. operatorRequisites().
 */

