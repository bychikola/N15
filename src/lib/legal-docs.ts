// --- Типы ------------------------------------------------------------------------

export interface LegalSection {
  title: string
  /** Абзацы разделяются переводом строки: пустая строка — новый абзац */
  text: string
}

export type LegalDocId =
  | 'personal-data-consent'
  | 'privacy-policy'
  | 'callback-consent'
  | 'user-agreement'
  | 'placement-offer'
  | 'placement-rules'
  | 'owner-media-consent'
  | 'ad-placement-consent'
  // Документы, которые жили на сайте раньше и остаются на своих страницах:
  // рекламная оферта, правила рекламы и правила доски объявлений. В списке
  // раздела «Документы» они не повторяются (там на них ведут ссылки форм), но
  // печатная форма и выгрузка нужны и им — иначе кнопок не было бы на четырёх
  // страницах, которые уже открывают посетители
  | 'advertising-offer'
  | 'advertising-rules'
  | 'board-rules'

export interface LegalDoc {
  id: LegalDocId
  /** Адрес страницы без языка: /{lang}{path} */
  path: string
  /** Полное название документа — как в шапке страницы и в файле */
  title: string
  /** Название для ссылок и списков */
  short: string
  subtitle: string
  /** Редакция словами и её номер: показываются рядом с датой документа */
  updated: string
  version: string
  /** Вводный абзац перед разделами */
  intro: string
  sections: LegalSection[]
  /** Оговорка под текстом (необязательно) */
  note?: string
  /**
   * Редакции, из которых документ составлен. Заполнено у составных
   * документов: их текст не пишется заново, а собирается из действующих
   * правил, поэтому вместо версии показываются версии источников.
   */
  sources?: string[]
}

