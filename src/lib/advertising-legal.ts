/** Ключи согласий: совпадают с полями заявки (consentOffer, consentRights, consent) */
export type AdConsentKey = 'offer' | 'rights' | 'data'

export interface AdConsentLink {
  /** Путь документа без языка */
  path: string
  /** Название документа для ссылки */
  title: string
}

export interface AdConsent {
  key: AdConsentKey
  /** Поле заявки, в которое пишется отметка */
  field: 'consentOffer' | 'consentRights' | 'consent'
  /** Ссылки на документы, которые открываются из этой галочки */
  links: AdConsentLink[]
}

